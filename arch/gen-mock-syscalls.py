#!/usr/bin/env python3
"""Generate mock syscall name tables from the pinned Linux source tree."""

import argparse
import hashlib
import pathlib
import re
import subprocess
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
FILES = {
    "arch/x86/entry/syscalls/syscall_32.tbl": "35e8f92867546f26da386786bbe6599d720269f78db9ce305b7ca3a403052401",
    "arch/x86/entry/syscalls/syscall_64.tbl": "e9b7c646fcf5d3e0aee64dabd7baae799771ee5e24f13277577a35170e9ba2e0",
    "arch/arm64/include/uapi/asm/unistd.h": "a1d29b1442eab1f7fc50184df7ad7271c9d48fa1dabd0e413e88017a26a245cc",
    "include/uapi/asm-generic/unistd.h": "026f4f7efe79d01bdcaacab2be80d14b15396839bd2f80957c8ad72357e459f9",
}


def x86_table(path, abis):
    result = {}
    for line in path.read_text().splitlines():
        fields = line.split()
        if len(fields) >= 3 and fields[0].isdigit() and fields[1] in abis:
            number, _, name = fields[:3]
            if name in result:
                raise ValueError("duplicate syscall name " + name)
            result[name] = int(number)
    return result


def arm64_table(linux, cc):
    # The only architecture dependency of this UAPI header is bitsperlong.
    # Supply the arm64 value explicitly, rather than using the host's header.
    with tempfile.TemporaryDirectory(prefix="bst-syscalls-") as temp:
        include = pathlib.Path(temp)
        (include / "asm").mkdir()
        (include / "asm/bitsperlong.h").write_text("#define __BITS_PER_LONG 64\n")
        output = subprocess.check_output([
            cc, "-E", "-dM", "-undef", "-nostdinc", "-I", str(include),
            "-I", str(linux / "include/uapi"),
            str(linux / "arch/arm64/include/uapi/asm/unistd.h"),
        ], text=True)
    macros = dict(re.findall(r"^#define (__NR\w+) (\w+)$", output, re.M))

    def value(macro):
        seen = set()
        while not macro.isdigit():
            if macro in seen or macro not in macros:
                raise ValueError("cannot resolve " + macro)
            seen.add(macro)
            macro = macros[macro]
        return int(macro)

    return {name[5:]: value(val) for name, val in macros.items()
            if name.startswith("__NR_") and name not in
            ("__NR_syscalls", "__NR_arch_specific_syscall")}


def write_table(path, tables):
    lines = ["/* Generated by arch/gen-mock-syscalls.py from Linux v6.6. */", ""]
    for name, entries in tables:
        lines.append("static const struct mock_syscall_name %s[] = {" % name)
        for syscall, number in sorted(entries.items()):
            lines.append('\t{ "%s", %d },' % (syscall, number))
        lines.extend(["};", ""])
    path.write_text("\n".join(lines))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("linux", type=pathlib.Path, help="Linux v6.6 source tree")
    parser.add_argument("--cc", default="cc", help="C preprocessor compiler")
    args = parser.parse_args()
    for name, digest in FILES.items():
        if hashlib.sha256((args.linux / name).read_bytes()).hexdigest() != digest:
            raise ValueError("unexpected Linux source contents: " + name)
    x86 = args.linux / "arch/x86/entry/syscalls"
    write_table(ROOT / "arch/x86/mock-syscalls.inc", [
        ("names_x86_64", x86_table(x86 / "syscall_64.tbl", {"common", "64"})),
        ("names_i386", x86_table(x86 / "syscall_32.tbl", {"i386"})),
        ("names_x32", x86_table(x86 / "syscall_64.tbl", {"common", "x32"})),
    ])
    write_table(ROOT / "arch/aarch64/mock-syscalls.inc", [
        ("names_aarch64", arm64_table(args.linux, args.cc)),
    ])


if __name__ == "__main__":
    main()
